const I18nCtx = React.createContext({ lang: 'en', t: (k) => k });

const I18nProvider = ({ lang, children }) => {
  const t = React.useCallback((key, ...args) => {
    const dict = I18N[lang] || I18N.en;
    const v = dict[key];
    if (typeof v === 'function') return v(...args);
    if (v == null) return I18N.en[key] || key;
    return v;
  }, [lang]);
  return <I18nCtx.Provider value={{ lang, t }}>{children}</I18nCtx.Provider>;
};

const useT = () => React.useContext(I18nCtx);

// Localized number/date formatting
const fmtIDRLocal = (n, lang) => {
  if (n >= 1e9) {
    const v = (n / 1e9).toFixed(2).replace(/\.?0+$/, '');
    return lang === 'id' ? `Rp\u00A0${v.replace('.', ',')} M` : `Rp\u00A0${v} M`;
  }
  if (n >= 1e6) {
    const v = (n / 1e6).toFixed(0);
    return `Rp\u00A0${v} jt`;
  }
  return 'Rp\u00A0' + n.toLocaleString(lang === 'id' ? 'id-ID' : 'en-US');
};

export { I18N, I18nProvider, useT, fmtIDRLocal };
